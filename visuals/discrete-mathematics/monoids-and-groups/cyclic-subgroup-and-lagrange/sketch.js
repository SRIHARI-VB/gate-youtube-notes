/* Cyclic subgroups and Lagrange's theorem inside Z_12.
   Every number shown here is recomputed in scripts/validate.py (check_monoids_and_groups):
   the multiples of 4, the four cosets of <4>, the twelve multiples of 5, the four generators
   of Z_12, the six subgroup orders and the largest proper subgroup order. */
var N = 12;

/* The ring of residues: 0 at the top, then clockwise. */
function pos(k, w, h) {
  var cx = w * 0.40, cy = h * 0.56, r = Math.min(w * 0.30, h * 0.40);
  var ang = -Math.PI / 2 + 2 * Math.PI * k / N;
  return [cx + r * Math.cos(ang), cy + r * Math.sin(ang)];
}

function ink() {
  var dark = window.matchMedia && window.matchMedia('(prefers-color-scheme: dark)').matches;
  background(dark ? color(23, 28, 36) : color(255));
  noStroke(); fill(dark ? color(238, 241, 245) : color(20, 24, 31));
  textFont('ui-sans-serif, system-ui, -apple-system, Segoe UI, Arial');
}
function head(t, x, y) { textSize(16); textStyle(BOLD); text(t, x, y); textStyle(NORMAL); }
function note(t, x, y) { textSize(12.5); fill(90, 100, 116); noStroke(); text(t, x, y); }
function panel(x, y, lines, w) {
  noStroke(); fill(232, 238, 255);
  var bw = Math.min(w - x - 12, 214);
  rect(x, y, bw, 22 + lines.length * 20, 8);
  fill(31, 94, 255); textSize(12); textStyle(BOLD); text('what the diagram shows', x + 10, y + 17);
  textStyle(NORMAL); textSize(11.5); fill(31, 60, 140);
  for (var i = 0; i < lines.length; i++) { text(lines[i], x + 10, y + 36 + i * 19); }
}

var NEUTRAL_DARK = [120, 130, 145], NEUTRAL_LIGHT = [190, 196, 206];

/* The twelve residues, with an optional colour per residue and an optional orbit polyline. */
function ring(opt, w, h) {
  var dark = window.matchMedia && window.matchMedia('(prefers-color-scheme: dark)').matches;
  var colours = opt.colours || {};
  var orbit = opt.orbit || [];
  for (var i = 0; i < orbit.length - 1; i++) {
    var A = pos(orbit[i], w, h), B = pos(orbit[i + 1], w, h);
    stroke(31, 94, 255); strokeWeight(2.2); line(A[0], A[1], B[0], B[1]);
  }
  for (var k = 0; k < N; k++) {
    var P = pos(k, w, h);
    var c = colours[k];
    if (c) { noStroke(); fill(c[0], c[1], c[2]); }
    else { noStroke(); fill(dark ? NEUTRAL_DARK[0] : NEUTRAL_LIGHT[0], dark ? NEUTRAL_DARK[1] : NEUTRAL_LIGHT[1], dark ? NEUTRAL_DARK[2] : NEUTRAL_LIGHT[2]); }
    var size = c ? 26 : 20;
    circle(P[0], P[1], size);
    if (c) {
      fill(255); textSize(12); textStyle(BOLD); textAlign(CENTER, CENTER);
      text(String(k), P[0], P[1]); textAlign('left', 'baseline'); textStyle(NORMAL);
    } else {
      fill(dark ? color(20, 24, 31) : color(255)); textSize(11); textAlign(CENTER, CENTER);
      text(String(k), P[0], P[1]); textAlign('left', 'baseline');
    }
  }
}

